"""Run the required end-to-end scenario and write docs/verification/scenario-run.md. Exit 1 if any check fails."""

# Lazy annotations.
from __future__ import annotations

# sys.path setup.
import sys

# Path arithmetic.
from pathlib import Path

# The repository root.
ROOT = Path(__file__).resolve().parents[1]
# Make the tests package importable.
sys.path.insert(0, str(ROOT))
# Make the service package importable.
sys.path.insert(0, str(ROOT / "src"))

# The scripted end-to-end scenario shared with the test suite.
from tests.scenario_flow import run_scenario


# Run the scenario and write its report.
def main() -> int:
    # Run it: scripted model, fixed clock, real services.
    b = run_scenario()
    # The threshold scorecard computed during the run.
    sc = b.scorecard
    # Build the markdown report: header, transcript, then the checks table.
    lines = [
        "# Scenario run", "",
        ("Generated by `python scripts/run_scenario.py`. Clock fixed at 2026-08-04 09:35 IST; the supplied snapshot plus labelled "
        "`TEST_FIXTURE` labour and consignee evidence; driver messages are fixed text and the model is a **script**, so this run is "
        "repeatable and shows what the deterministic layers do. It says nothing about how a real model behaves."), "",
        "## Transcript", "", "```", b.text(), "```", "", "## Checks", "", "| # | Check | Result |", "|---|---|---|",
    ]
    # One table row per check.
    lines += [f"| {i} | {c.name} | {'PASS' if c.ok else 'FAIL'} |" for i, c in enumerate(b.checks, 1)]
    # How many checks passed.
    passed = sum(c.ok for c in b.checks)
    # Add the pass count and the threshold scorecard.
    lines += ["", f"**{passed}/{len(b.checks)} checks passed.**", "", "## Threshold scorecard (numerator / denominator)", "",
              "| Threshold | Measured | Notes |", "|---|---|---|",
              f"| Zero conflicting allocations | {sc['conflicting_allocations']['numerator']} violations | {sc['conflicting_allocations']['note']} |",
              f"| Zero unauthorised cross-driver reads | {sc['cross_driver_reads']['succeeded']} succeeded of {sc['cross_driver_reads']['attempted']} attempted ({sc['cross_driver_reads']['refused']} refused) | one scripted attempt |",
              f"| 100% state-backed confirmations | {sc['state_backed_confirmations']['numerator']} / {sc['state_backed_confirmations']['denominator']} | {sc['state_backed_confirmations']['note']} |",
              f"| 100% complete no-slot hand-offs | {sc['complete_handoffs']['numerator']} / {sc['complete_handoffs']['denominator']} | all hand-offs, not only no-slot |",
              f"| Evaluator checks | {sc['evaluator_checks']['passed']} / {sc['evaluator_checks']['total']} | {sc['evaluator_checks']['by_evaluator']} |",
              "| Median clarification turns | not judged | one scripted clarification; a script is not a model |",
              f"| >= 80% automatic resolution | {sc['resolved_without_a_person']['numerator']} / {sc['resolved_without_a_person']['denominator']} drivers | {sc['resolved_without_a_person']['note']}; not judged |", "",
              ("The operational thresholds that depend on a real model, real traffic or a real labour feed are **not** demonstrated by this run "
              "(see `client-readout.md`)."), ""]
    # The report file.
    out = ROOT / "docs" / "verification" / "scenario-run.md"
    # Write it.
    out.write_text("\n".join(lines), encoding="utf-8")
    # Also print the transcript.
    print(b.text())
    # And the summary line.
    print(f"\n{passed}/{len(b.checks)} checks passed; wrote {out}")
    # Exit non-zero if any check failed.
    return 0 if b.ok else 1


# Run main when executed as a script.
if __name__ == "__main__":
    raise SystemExit(main())
